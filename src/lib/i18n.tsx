export type TKey = keyof (typeof dict)["de"];

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  fmtDate: (ymd: string) => string;
  fmtHours: (h: number) => string;
}
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // Language comes from the signed-in user's saved setting; default is German.
  const qc = useQueryClient();
  const { data: me } = useQuery(meQuery);
  const [override, setOverride] = useState<Lang | null>(null);
  const lang: Lang = override ?? (me?.language === "en" ? "en" : "de");
  useEffect(() => {
    localStorage.setItem("lucesem-lang", lang); // read by pop-up notifications only
  }, [lang]);
  useEffect(() => {
    // A language picked before signing in is saved to the account once signed in.
    if (me && override && override !== me.language) {
      qc.setQueryData(meQuery.queryKey, { ...me, language: override } as never);
      setMyLanguage({ data: { language: override } }).catch(() => {});
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [me?.id]);
  const setLang = (l: Lang) => {
    setOverride(l);
    if (me) {
      qc.setQueryData(meQuery.queryKey, { ...me, language: l } as never);
      setMyLanguage({ data: { language: l } }).catch(() => {});
    }
  };
  const locale = lang === "de" ? "de-AT" : "en-US";
  const value: I18n = {
    lang,
    setLang,
    t: (k) => dict[lang][k] ?? k,
    fmtDate: (s) => {
      const [y, m, d] = s.split("-");
      return lang === "de" ? `${d}.${m}.${y}` : `${m}/${d}/${y}`;
    },
    fmtHours: (h) =>
      `${h.toLocaleString(locale, { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${dict[lang].hours}`,
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
